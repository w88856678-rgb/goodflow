#!/usr/bin/env python3
from __future__ import annotations

import argparse
import json
from pathlib import Path

from PIL import Image, ImageOps


EXTENSIONS = {".png", ".jpg", ".jpeg", ".webp"}


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Import keyframes generated by an agent-native or external image tool."
    )
    parser.add_argument("project")
    parser.add_argument("source_dir")
    parser.add_argument("--width", type=int, default=1080)
    parser.add_argument("--height", type=int, default=1920)
    args = parser.parse_args()

    project_dir = Path(args.project).expanduser().resolve()
    source_dir = Path(args.source_dir).expanduser().resolve()
    project = json.loads((project_dir / "project.json").read_text(encoding="utf-8"))
    targets = project.get("assets", {}).get("keyframes", [])
    sources = sorted(
        path for path in source_dir.iterdir()
        if path.is_file() and path.suffix.lower() in EXTENSIONS
    )
    if len(sources) < len(targets):
        raise SystemExit(f"Need {len(targets)} images, found {len(sources)} in {source_dir}")

    for index, (source, item) in enumerate(zip(sources, targets), 1):
        relative = item["path"] if isinstance(item, dict) else str(item)
        target = project_dir / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        with Image.open(source).convert("RGB") as image:
            fitted = ImageOps.fit(
                image, (args.width, args.height), method=Image.Resampling.LANCZOS,
                centering=(0.5, 0.5),
            )
            fitted.save(target, format="PNG", optimize=True)
        print(f"{index:02d}\t{source}\t{target}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
